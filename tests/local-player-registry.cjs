const assert = require('node:assert/strict')
const { EventEmitter } = require('node:events')
const { createLocalPlayerRegistry } = require('../src/main/localPlayerRegistry.cjs')

class Sender extends EventEmitter {
  constructor(id) { super(); this.id = id; this.destroyed = false }
  isDestroyed() { return this.destroyed }
}
const transitions = []
const registry = createLocalPlayerRegistry({ setServerActive: active => transitions.push(active) })
const video = new Sender(1), music = new Sender(2)
const state = (title, playing) => ({ title, artist: 'artist', playing, videoId: 'abcdefghijk', durationMs: 5000, progressMs: 2000 })
registry.setPlayer(video, state('Video', true))
assert.equal(transitions.at(-1), true, 'ordinary Watch player starts adapter')
assert.equal(registry.activePlayer().state.title, 'Video')
assert.equal(registry.activePlayer(true), undefined, 'video never becomes a legacy music player')
assert.equal(registry.hasMusic(), false)
registry.setMusic(music, true)
registry.setPlayer(music, state('Music', false))
assert.equal(registry.activePlayer().state.title, 'Video', 'prefer playing over paused')
assert.equal(registry.activePlayer(true).state.title, 'Music', 'legacy selects only Music')
registry.setPlayer(music, state('Music', true))
assert.equal(registry.activePlayer().state.title, 'Music', 'prefer most recently updated playing player')
registry.setMusic(music, false)
assert.equal(registry.activePlayer(true), undefined)
assert.equal(registry.activePlayer().state.title, 'Music', 'adapter can still use an ordinary watch after leaving Music')
registry.setPlayer(music, null)
assert.equal(registry.activePlayer().state.title, 'Video')
video.emit('did-start-navigation', {}, 'url', true, true)
assert.equal(registry.activePlayer().state.title, 'Video', 'in-page navigation does not erase active state')
video.emit('did-start-navigation', {}, 'url', false, true)
assert.equal(registry.activePlayer(), undefined)
assert.equal(transitions.at(-1), false, 'server stops when neither a player nor Music remain')
registry.setMusic(music, true)
assert.equal(transitions.at(-1), true, 'Music search keeps legacy API alive without a player')
music.emit('render-process-gone')
assert.equal(registry.hasMusic(), false)
assert.equal(transitions.at(-1), false)
registry.setPlayer(video, state('Other', true))
video.destroyed = true
video.emit('destroyed')
assert.equal(registry.activePlayer(), undefined)
assert.equal(transitions.at(-1), false)
console.log('Local player registry lifecycle tests passed')
