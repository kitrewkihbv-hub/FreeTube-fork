const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const source = fs.readFileSync('integrations/ubersicht/dynamic-island-2.jsx', 'utf8')
const parseStart = source.indexOf('const parseMacTube = '), parseEnd = source.indexOf('const ingest = ', parseStart)
assert.ok(parseStart >= 0 && parseEnd > parseStart)
const parse = vm.runInNewContext(`(()=>{${source.slice(parseStart, parseEnd)};return parseMacTube})()`, {
  atob: value => Buffer.from(value, 'base64').toString('binary'), decodeURIComponent, Array, JSON, Number,
})
const encode = value => Buffer.from(JSON.stringify(value)).toString('base64')
const video = parse(encode({ playerState: 1, videoData: { video_id: 'abcdefghijk', title: 'Café 🐱', author: 'Channel' }, currentTime: 12.5, duration: 120, thumbnailUrl: 'https://i.ytimg.com/vi/abcdefghijk/mqdefault.jpg' }))
assert.equal(video.app, 'mactube'); assert.equal(video.mode, 'video'); assert.equal(video.title, 'Café 🐱'); assert.equal(video.pos, 12.5); assert.equal(video.playing, true)
const music = parse(encode({ is_playing: false, progress_ms: 4500, item: { id: 'abcdefghijk', name: 'Track', duration_ms: 123000, artists: [{ name: 'Artist' }], album: { images: [{ url: 'https://i.ytimg.com/vi/abcdefghijk/mqdefault.jpg' }] } } }))
assert.equal(music.mode, 'music'); assert.equal(music.playing, false); assert.equal(music.dur, 123); assert.equal(music.pos, 4.5)
assert.equal(parse(encode({ videoData: { video_id: 'bad' }, playerState: 1 })), null)
assert.equal(parse('invalid-data'), null)
const start = source.indexOf('const media = (m, act) => {'), end = source.indexOf('const fetchMusicArt', start)
assert.ok(start >= 0 && end > start)
const commands = []
const media = vm.runInNewContext(`(()=>{${source.slice(start, end)};return media})()`, {
  run: cmd => { commands.push(cmd); return Promise.resolve() }, Number, Object, ytRun() {}, YT_CTL: {}
})
media(video, 'playpause'); media(video, 'next'); media(video, 'prev'); media(video, { seek: 4.2 })
media(music, 'playpause'); media(music, { seek: 3.5 }); media(music, { seek: Infinity }); media(music, { seek: 200 })
assert.match(commands[0], /-X POST .*\/youtube\/player\/pauseVideo/)
assert.match(commands[1], /\/youtube\/player\/nextVideo/)
assert.match(commands[2], /\/youtube\/player\/previousVideo/)
assert.match(commands[3], /\/youtube\/player\/seekTo\?seconds=4\.20/)
assert.match(commands[4], /-X PUT .*\/v1\/me\/player\/play/)
assert.match(commands[5], /-X PUT .*\/v1\/me\/player\/seek\?position_ms=3500/)
assert.equal(commands.length, 6, 'invalid seeks do not issue requests')
// Evaluate and run the actual polling shell with harmless mocked macOS tools.
const shellStart = source.indexOf('const BROWSERS = ')
const shellEnd = source.indexOf('/* ───────────────────────── TIMER PERSISTENCE', shellStart)
assert.ok(shellStart >= 0 && shellEnd > shellStart)
const shell = vm.runInNewContext(`(()=>{${source.slice(shellStart, shellEnd).replace('export const command =', 'const command =')};return command})()`)
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'mactube-widget-v3-'))
try {
  const bin = path.join(temp, 'bin'); fs.mkdirSync(bin)
  const fake = (name, text) => fs.writeFileSync(path.join(bin, name), `#!/bin/sh\n${text}\n`, { mode: 0o755 })
  fake('pgrep', 'exit 1'); fake('pmset', 'exit 0'); fake('osascript', 'exit 0')
  fake('curl', `case "$*" in *youtube/player*) printf '%s' "$FAKE_VIDEO";; *v1/me/player*) printf '%s' "$FAKE_MUSIC";; esac`)
  const rawVideo = JSON.stringify({ playerState: 1, videoData: { video_id: 'abcdefghijk', title: 'Café', author: 'Creator' }, currentTime: 1, duration: 4 })
  const out = execFileSync('/bin/sh', ['-c', shell], { encoding: 'utf8', env: { ...process.env, PATH: `${bin}:${process.env.PATH}`, FAKE_VIDEO: rawVideo, FAKE_MUSIC: '' } })
  const lines = out.split('\n'); const found = lines.indexOf('###DI-MACTUBE_VIDEO')
  assert.ok(found >= 0); assert.equal(Buffer.from(lines[found + 1], 'base64').toString('utf8'), rawVideo)
  assert.equal(parse(lines[found + 1]).title, 'Café')
  assert.equal(lines[lines.indexOf('###DI-MACTUBE_MUSIC') + 1], '')
} finally { fs.rmSync(temp, { recursive: true, force: true }) }
assert.match(source, /###DI-MACTUBE_VIDEO/)
assert.match(source, /###DI-MACTUBE_MUSIC/)
assert.match(source, /parseTrack\(sec\.SPOT, 'spotify'\)/, 'original Spotify integration remains')
assert.match(source, /parseTrack\(ytLine, 'youtube'\)/, 'original browser YouTube integration remains')
console.log('Updated Übersicht widget bridge tests passed')
