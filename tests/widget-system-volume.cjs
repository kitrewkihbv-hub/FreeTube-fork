const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const source = fs.readFileSync('integrations/ubersicht/dynamic-island-new-mactube.jsx', 'utf8')
const start = source.indexOf('const setT = '), end = source.indexOf('const sections = ', start)
assert.ok(start >= 0 && end > start)
const ingestVolume = vm.runInNewContext(`(()=>{${source.slice(start, end)};return ingestVolume})()`, { Date, Number, Math })
let state = { volume: null, muted: false, transient: null }
state = ingestVolume(state, '35,false\n')
assert.equal(state.volume, 35); assert.equal(state.transient, null, 'initial value does not produce a false popup')
state = ingestVolume(state, '40,false\n')
assert.equal(state.volume, 40); assert.equal(state.transient.kind, 'volume'); assert.ok(state.transient.until > Date.now())
state = ingestVolume(state, '40,true')
assert.equal(state.muted, true); assert.equal(state.transient.kind, 'volume')
const before = state; state = ingestVolume(state, 'not-a-volume')
assert.strictEqual(state, before, 'errors do not overwrite the last real volume')
state = ingestVolume({ ...state, transient: { kind: 'timerdone', until: Date.now() + 5000 } }, '50,false')
assert.equal(state.volume, 50); assert.equal(state.transient.kind, 'timerdone', 'alarm retains priority')
assert.match(source, /setInterval\(pollVolume, 250\)/)
assert.match(source, /if \(volumePollBusy\) return/)
assert.match(source, /case 'DI_SYSVOL': return ingestVolume\(prev, event\.out\)/)
assert.doesNotMatch(source, /echo "###DI-VOL"/, 'slow status poll cannot overwrite fresher volume')
console.log('Fast system volume widget tests passed')
